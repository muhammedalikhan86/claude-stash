<#
.SYNOPSIS
  Builds agents/plugin-orchestrated-developer-high.md and -xhigh.md from agents/orchestrated-developer.md.

.DESCRIPTION
  Why these files exist: `model` and `effort` can only be set in an agent definition's frontmatter.
  The Agent tool takes a `model` parameter but no `effort` one, so plugin-orchestrator-development-pattern
  raises a Developer's reasoning effort by choosing between sibling definitions:
    high  - the working level for a first or second attempt: room for real design judgment, without
            spending an escalation budget not yet earned.
    xhigh - the last-retry level, used only at loop_count 3, the one attempt before a human is paged.
            It needs extended thinking on; with thinking off it is downgraded to high automatically.

  Why generated copies, not shims: a shim that says "read orchestrated-developer.md" costs the spawned
  Developer an extra turn, and the text it reads lands outside the cacheable system prompt. A full copy
  avoids both; generating it keeps orchestrated-developer.md the one source of truth.

  Each file keeps its own frontmatter (name, description, tools, model, effort). Everything after the
  frontmatter is replaced by a banner and the body of orchestrated-developer.md. No plugin-specific text
  is added: staying inside the component and leaving the platform contract alone are both stated by the
  Task Packet's `## Component` and `## Architecture Reference` sections.

.EXAMPLE
  .\scripts\build-developer-agents.ps1          # rewrite both files
  .\scripts\build-developer-agents.ps1 -Check   # write nothing; exit 1 if either file is stale
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = "Stop"
$agents = Join-Path (Split-Path $PSScriptRoot -Parent) "agents"
$targets = "plugin-orchestrated-developer-high.md", "plugin-orchestrated-developer-xhigh.md"
$banner = "<!-- GENERATED by scripts/build-developer-agents.ps1 from agents/orchestrated-developer.md. Edit that file, then re-run the script. -->"

function Assert-Exists([string]$Path) {
    if (Test-Path -LiteralPath $Path -PathType Leaf) { return }
    if ($Check) { Write-Host "[MISSING] $Path"; exit 1 }
    throw "Missing file: $Path"
}

function Split-Frontmatter([string]$Path) {
    Assert-Exists $Path
    $text = [IO.File]::ReadAllText($Path).Replace("`r`n", "`n")
    if ($text -notmatch '(?s)^(---\n.*?\n---\n)(.*)$') { throw "No frontmatter in $Path" }
    return $Matches[1], $Matches[2]
}

$body = (Split-Frontmatter (Join-Path $agents "orchestrated-developer.md"))[1].TrimStart("`n")
$stale = 0
foreach ($name in $targets) {
    $path = Join-Path $agents $name
    $front = (Split-Frontmatter $path)[0]
    $want = "$front`n$banner`n`n$body"
    $have = [IO.File]::ReadAllText($path).Replace("`r`n", "`n")
    if ($have -ceq $want) { Write-Host "[OK]     $name"; continue }
    if ($Check) { Write-Host "[STALE]  $name"; $stale++; continue }
    [IO.File]::WriteAllText($path, $want, [Text.UTF8Encoding]::new($false))
    Write-Host "[BUILT]  $name" -ForegroundColor Green
}
if ($stale) { exit 1 }
